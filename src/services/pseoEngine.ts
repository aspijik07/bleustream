// Programmatic SEO (pSEO) Automated Article Generation Engine for BleuStream
// Generates 10 high-ranking, keyword-dense articles daily from TMDB Trending Movies, TV Series & Anime

import { SEOArticle, SEO_ARTICLES } from '../data/seoArticles';
import { fetchTrending, fetchAnime, getPosterUrl, getBackdropUrl } from './tmdb';
import { MediaItem } from '../types';

const STORAGE_KEY_ARTICLES = 'bleustream_pseo_articles_v1';
const STORAGE_KEY_LAST_DATE = 'bleustream_pseo_last_gen_date';
const STORAGE_KEY_SETTINGS = 'bleustream_pseo_settings_v1';

export interface PSEOSettings {
  autoGenerateDaily: boolean;
  targetKeywordsStrategy: 'aggressive' | 'balanced' | 'long_tail';
  articlesPerDay: number;
  includeMovies: boolean;
  includeSeries: boolean;
  includeAnime: boolean;
  minWordCount: number;
  lastGeneratedDate: string | null;
}

const DEFAULT_SETTINGS: PSEOSettings = {
  autoGenerateDaily: true,
  targetKeywordsStrategy: 'aggressive',
  articlesPerDay: 10,
  includeMovies: true,
  includeSeries: true,
  includeAnime: true,
  minWordCount: 850,
  lastGeneratedDate: null,
};

