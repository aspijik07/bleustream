class PSEOEngineService {
  private customArticles: SEOArticle[] = [];
  private settings: PSEOSettings = DEFAULT_SETTINGS;
  private isGenerating = false;
  private listeners: Array<() => void> = [];

  constructor() {
    this.loadState();
    // Run automated check if today's articles are generated
    if (typeof window !== 'undefined') {
      setTimeout(() => {
        this.checkAndAutoGenerate();
      }, 3000);
    }
  }

  private loadState() {
    if (typeof window === 'undefined') return;

    try {
      const savedArticles = localStorage.getItem(STORAGE_KEY_ARTICLES);
      if (savedArticles) {
        this.customArticles = JSON.parse(savedArticles);
      }

      const savedSettings = localStorage.getItem(STORAGE_KEY_SETTINGS);
      if (savedSettings) {
        this.settings = { ...DEFAULT_SETTINGS, ...JSON.parse(savedSettings) };
      }

      const lastDate = localStorage.getItem(STORAGE_KEY_LAST_DATE);
      if (lastDate) {
        this.settings.lastGeneratedDate = lastDate;
      }
    } catch (e) {
      console.warn('Error loading pSEO state:', e);
    }
  }

  private saveState() {
    if (typeof window === 'undefined') return;
    try {
      localStorage.setItem(STORAGE_KEY_ARTICLES, JSON.stringify(this.customArticles));
      localStorage.setItem(STORAGE_KEY_SETTINGS, JSON.stringify(this.settings));
      if (this.settings.lastGeneratedDate) {
        localStorage.setItem(STORAGE_KEY_LAST_DATE, this.settings.lastGeneratedDate);
      }
    } catch (e) {
      console.warn('Error saving pSEO state:', e);
    }
    this.notify();
  }

  private notify() {
    this.listeners.forEach((cb) => {
      try {
        cb();
      } catch {
        // ignore
      }
    });
  }

  public subscribe(cb: () => void): () => void {
    this.listeners.push(cb);
    return () => {
      this.listeners = this.listeners.filter((l) => l !== cb);
    };
  }

  public getAllArticles(): SEOArticle[] {
    // Return custom generated articles first, followed by baseline curated articles
    const map = new Map<string, SEOArticle>();

    // Add baseline curated articles
    SEO_ARTICLES.forEach((a) => map.set(a.slug, a));

    // Override or append dynamically generated articles
    this.customArticles.forEach((a) => map.set(a.slug, a));

    return Array.from(map.values()).sort((a, b) => {
      return (b.publishedDate || '').localeCompare(a.publishedDate || '');
    });
  }

  public getGeneratedArticles(): SEOArticle[] {
    return [...this.customArticles];
  }

  public getSettings(): PSEOSettings {
    return { ...this.settings };
  }

  public updateSettings(partial: Partial<PSEOSettings>): PSEOSettings {
    this.settings = { ...this.settings, ...partial };
    this.saveState();
    return this.getSettings();
  }

  public async checkAndAutoGenerate(): Promise<boolean> {
    if (!this.settings.autoGenerateDaily) return false;

    const today = new Date().toISOString().split('T')[0];
    if (this.settings.lastGeneratedDate === today && this.customArticles.length >= 10) {
      return false; // Already generated for today
    }

    try {
      await this.generateDailyTrendingArticles(false);
      return true;
    } catch (err) {
      console.warn('Automated pSEO generation check error:', err);
      return false;
    }
  }

  // Generates 10 top trending articles (4 movies, 3 tv series, 3 anime)
  public async generateDailyTrendingArticles(force = true): Promise<SEOArticle[]> {
    if (this.isGenerating) return [];
    this.isGenerating = true;

    try {
      const today = new Date().toISOString().split('T')[0];

      // 1. Fetch trending movies, tv series, and anime from TMDB API
      const [moviesRes, tvRes, animeRes] = await Promise.all([
        fetchTrending('movie', 'day').catch(() => []),
        fetchTrending('tv', 'day').catch(() => []),
        fetchAnime('all', 1).catch(() => []),
      ]);

      const newArticles: SEOArticle[] = [];

      // 4 Top Trending Movies
      const topMovies = moviesRes.slice(0, 4);
      topMovies.forEach((m) => {
        newArticles.push(synthesizeArticleForMedia(m, 'Movie Guides'));
      });

      // 3 Top Trending TV Series
      const topSeries = tvRes.slice(0, 3);
      topSeries.forEach((s) => {
        newArticles.push(synthesizeArticleForMedia(s, 'TV Series Guides'));
      });

      // 3 Top Trending Anime
      const topAnime = animeRes.slice(0, 3);
      topAnime.forEach((a) => {
        newArticles.push(synthesizeArticleForMedia(a, 'Anime Guides'));
      });

      if (newArticles.length === 0) {
        throw new Error('No trending titles returned from catalog API');
      }

      // Merge avoiding duplicate slugs
      const existingSlugs = new Set(this.customArticles.map((a) => a.slug));
      const addedArticles: SEOArticle[] = [];

      newArticles.forEach((art) => {
        if (!existingSlugs.has(art.slug)) {
          this.customArticles.unshift(art);
          addedArticles.push(art);
          existingSlugs.add(art.slug);
        }
      });

      this.settings.lastGeneratedDate = today;
      this.saveState();
      return addedArticles;
    } finally {
      this.isGenerating = false;
    }
  }

  public deleteArticle(idOrSlug: string): boolean {
    const beforeCount = this.customArticles.length;
    this.customArticles = this.customArticles.filter(
      (a) => a.id !== idOrSlug && a.slug !== idOrSlug
    );
    if (this.customArticles.length !== beforeCount) {
      this.saveState();
      return true;
    }
    return false;
  }

  public clearGeneratedArticles(): void {
    this.customArticles = [];
    this.settings.lastGeneratedDate = null;
    this.saveState();
  }

  public getStats() {
    const all = this.getAllArticles();
    const generated = this.customArticles;
    const today = new Date().toISOString().split('T')[0];

    const totalKeywords = all.reduce((sum, a) => sum + (a.keywords?.length || 0), 0);

    const categoriesCount = {
      movies: all.filter((a) => a.category === 'Movie Guides').length,
      series: all.filter((a) => a.category === 'TV Series Guides').length,
      anime: all.filter((a) => a.category === 'Anime Guides').length,
      curated: all.filter((a) => a.category === 'Curated Recommendations').length,
    };

    return {
      totalArticles: all.length,
      generatedCount: generated.length,
      curatedCount: SEO_ARTICLES.length,
      totalKeywordsTargeted: totalKeywords,
      lastGeneratedDate: this.settings.lastGeneratedDate,
      isGeneratedToday: this.settings.lastGeneratedDate === today,
      categoriesCount,
      estimatedMonthlySearchImpressions: all.length * 45000,
    };
  }
}

export const pseoEngine = new PSEOEngineService();
